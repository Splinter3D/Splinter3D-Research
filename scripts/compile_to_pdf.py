#!/usr/bin/env python3
"""
Splinter3D Research Report Builder

Compiles report/main.tex into a PDF, without polluting the source tree.

Generated files go to build/ , and are split in two:

    build/report/main.pdf    the final PDF (the only deliverable)
    build/intermediate/               intermediate files (.aux, .bbl, .log, ...)

The intermediate files are kept between builds, which makes rebuilds faster
and errors easier to investigate. Use --clean to remove them.

Usage (from anywhere, the script locates the repository by itself):

    python scripts/compile_to_pdf.py              # build, keep intermediate files
    python scripts/compile_to_pdf.py --clean      # remove intermediate files, keep the PDF
    python scripts/compile_to_pdf.py --purge      # remove the whole build/ directory
    python scripts/compile_to_pdf.py --check      # check project files and tools only

See scripts/README.md for details.
"""

from pathlib import Path
import argparse
import shutil
import subprocess
import sys


# ==========================================
# Configuration
# ==========================================

ROOT = Path(__file__).resolve().parent.parent

REPORT_DIR = ROOT / "report"

MAIN_FILE = REPORT_DIR / "main.tex"
BIB_FILE = REPORT_DIR / "references.bib"

# Everything generated by the build ends up in build/.
BUILD_DIR = ROOT / "build"

# Final deliverable only (the PDF).
BUILD_REPORT_DIR = BUILD_DIR / "report"

# Intermediate files (.aux, .bbl, .log, ...), kept for faster rebuilds.
# Do NOT name this directory "aux": it is a reserved device name on Windows
# (like con, prn, nul, com1...) and cannot be created there.
BUILD_INTERMEDIATE_DIR = BUILD_DIR / "intermediate"

# Final deliverable.
PDF_FILE = BUILD_REPORT_DIR / (MAIN_FILE.stem + ".pdf")

REQUIRED_FILES = [
    MAIN_FILE,
    BIB_FILE,
    REPORT_DIR / "sections/0_abstract.tex",
    REPORT_DIR / "sections/1_introduction.tex",
    REPORT_DIR / "sections/2_problem_definition.tex",
    REPORT_DIR / "sections/3_state_of_the_art.tex",
    REPORT_DIR / "sections/4_methodology.tex",
    REPORT_DIR / "sections/5_results.tex",
    REPORT_DIR / "sections/6_discussion.tex",
    REPORT_DIR / "sections/7_conclusion.tex",
]

REQUIRED_DIRECTORIES = [
    REPORT_DIR / "sections",
    REPORT_DIR / "figures",
]

REQUIRED_TOOLS = [
    "latexmk",
    "biber",
]

# Intermediate files that an old build (or a manual pdflatex run) may have
# left next to main.tex, directly inside report/.
LEGACY_SUFFIXES = (
    ".aux", ".bbl", ".bcf", ".blg", ".log", ".out", ".toc", ".lof", ".lot",
    ".fls", ".fdb_latexmk", ".run.xml", ".synctex.gz", ".xdv",
    ".nav", ".snm", ".vrb",
)


# ==========================================
# Utility Functions
# ==========================================

def print_error(message):
    print(f"[ERROR] {message}")


def print_warning(message):
    print(f"[WARN] {message}")


def print_success(message):
    print(f"[OK] {message}")


def print_info(message):
    print(f"[INFO] {message}")


def display_path(path):
    """Path relative to the repository root, for readable messages."""
    try:
        return path.relative_to(ROOT)
    except ValueError:
        return path


def remove_path(path):
    if path.is_dir() and not path.is_symlink():
        shutil.rmtree(path)
    else:
        path.unlink()


# ==========================================
# Environment Checks
# ==========================================

def check_path_safety():
    """
    TeX tools (and the TeX Live installer on Windows) can fail when the
    project path contains special characters. Only a warning: it may work.
    """
    path = str(ROOT)

    problems = []

    if not path.isascii():
        problems.append("non-ASCII characters (accents, etc.)")

    if " " in path:
        problems.append("spaces")

    if problems:
        print_warning(f"The project path contains {' and '.join(problems)}:")
        print(f"  {path}")
        print("  If the compilation fails mysteriously, move the repository to a")
        print("  simple path such as C:\\dev\\splinter3d-research (see scripts/README.md).")


def check_project_files():
    print_info("Checking project files...")

    missing = []

    for file in REQUIRED_FILES:
        if not file.is_file():
            missing.append(display_path(file))

    for directory in REQUIRED_DIRECTORIES:
        if not directory.is_dir():
            missing.append(display_path(directory))

    if missing:
        print_error("Missing project files/directories:")

        for item in missing:
            print(f"  - {item}")

        return False

    print_success("All required project files and directories are present.")
    return True


def check_tools():
    print_info("Checking required tools...")

    missing = []

    for tool in REQUIRED_TOOLS:
        executable = shutil.which(tool)

        if executable is None:
            missing.append(tool)
        else:
            print_success(f"{tool}: {executable}")

    if missing:
        print_error("Missing required tools:")

        for tool in missing:
            print(f"  - {tool}")

        print("\nPlease install a LaTeX distribution providing latexmk and biber")
        print("(TeX Live, or MacTeX on macOS). See scripts/README.md.")

        return False

    return True


def check_environment():
    print("\n========== Environment Check ==========\n")

    check_path_safety()

    files_ok = check_project_files()
    tools_ok = check_tools()

    print("\n=======================================\n")

    return files_ok and tools_ok


# ==========================================
# Clean
# ==========================================

def clean_build_directory():
    """
    Remove all intermediate files: the whole build/intermediate/ directory, and
    anything but the PDF in build/report/ (leftovers of older script versions).
    """
    removed = 0

    if BUILD_INTERMEDIATE_DIR.is_dir():
        removed += sum(1 for _ in BUILD_INTERMEDIATE_DIR.iterdir())
        shutil.rmtree(BUILD_INTERMEDIATE_DIR)

    if BUILD_REPORT_DIR.is_dir():
        for item in BUILD_REPORT_DIR.iterdir():
            if item == PDF_FILE:
                continue

            remove_path(item)
            removed += 1

    return removed


def clean_legacy_files():
    """Remove intermediate files left directly in report/ by older builds."""
    removed = 0

    for item in REPORT_DIR.glob(MAIN_FILE.stem + ".*"):
        if item.is_file() and item.name.endswith(LEGACY_SUFFIXES):
            item.unlink()
            removed += 1

    return removed


def clean():
    print_info("Cleaning intermediate files (the PDF is kept)...")

    try:
        removed = clean_build_directory() + clean_legacy_files()
    except OSError as error:
        print_error(f"Clean operation failed: {error}")
        return 1

    print_success(f"{removed} intermediate file(s)/directory(ies) removed.")

    if PDF_FILE.is_file():
        print_info(f"Kept: {display_path(PDF_FILE)}")

    return 0


def purge():
    print_info("Removing the whole build/ directory (PDF included)...")

    # Safety net: never delete anything outside <repo>/build
    if BUILD_DIR.resolve().parent != ROOT or BUILD_DIR.name != "build":
        print_error(f"Refusing to delete unexpected directory: {BUILD_DIR}")
        return 1

    try:
        if BUILD_DIR.exists():
            shutil.rmtree(BUILD_DIR)

        clean_legacy_files()
    except OSError as error:
        print_error(f"Purge failed: {error}")
        return 1

    print_success("build/ removed.")
    return 0


# ==========================================
# Build
# ==========================================

def build():
    if not check_environment():
        print_error("Build aborted.")
        return 1

    # Stale files from older builds next to main.tex can confuse latexmk
    # (it may pick them up instead of the ones in build/report/).
    removed = clean_legacy_files()

    if removed:
        print_info(f"Removed {removed} stale intermediate file(s) from report/.")

    # build/report/ must only contain the PDF: drop leftovers of older layouts.
    if BUILD_REPORT_DIR.is_dir():
        for item in BUILD_REPORT_DIR.iterdir():
            if item != PDF_FILE:
                remove_path(item)

    BUILD_REPORT_DIR.mkdir(parents=True, exist_ok=True)
    BUILD_INTERMEDIATE_DIR.mkdir(parents=True, exist_ok=True)

    print_info(
        f"Starting LaTeX compilation "
        f"(PDF: {display_path(BUILD_REPORT_DIR)}, "
        f"intermediate files: {display_path(BUILD_INTERMEDIATE_DIR)})..."
    )

    command = [
        shutil.which("latexmk"),
        "-pdf",
        "-interaction=nonstopmode",
        "-file-line-error",
        "-halt-on-error",
        f"-outdir={BUILD_REPORT_DIR}",
        f"-auxdir={BUILD_INTERMEDIATE_DIR}",
        MAIN_FILE.name,
    ]

    try:
        # cwd = report/ so that \input{sections/...}, \graphicspath and
        # references.bib keep resolving exactly as before.
        subprocess.run(command, cwd=REPORT_DIR, check=True)

    except subprocess.CalledProcessError:
        print_error("LaTeX compilation failed.")
        log_file = BUILD_INTERMEDIATE_DIR / (MAIN_FILE.stem + ".log")
        print_info(f"See the detailed log: {display_path(log_file)}")
        return 1

    except OSError as error:
        print_error(f"Could not execute latexmk: {error}")
        return 1

    if not PDF_FILE.is_file():
        print_error("Compilation reported success but no PDF was produced.")
        return 1

    # Legacy files from older builds must go in all cases.
    clean_legacy_files()

    print_info(f"Intermediate files kept in {display_path(BUILD_INTERMEDIATE_DIR)}/ (use --clean to remove them).")

    print_success(f"Build completed: {PDF_FILE}")
    return 0


# ==========================================
# Main
# ==========================================

def main():
    parser = argparse.ArgumentParser(
        description="Splinter3D Research Report Builder. "
                    f"Output: {display_path(PDF_FILE)}"
    )

    action = parser.add_mutually_exclusive_group()

    action.add_argument(
        "--clean",
        action="store_true",
        help="Remove intermediate files, keep the PDF."
    )

    action.add_argument(
        "--purge",
        action="store_true",
        help="Remove the whole build/ directory, PDF included."
    )

    action.add_argument(
        "--check",
        action="store_true",
        help="Check project files and required tools without compiling."
    )

    args = parser.parse_args()

    if args.clean:
        return clean()

    if args.purge:
        return purge()

    if args.check:
        return 0 if check_environment() else 1

    return build()


if __name__ == "__main__":
    sys.exit(main())
